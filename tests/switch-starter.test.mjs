import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import init,{Editor} from '../web/pkg/pixlprfct_core.js';
import {ensureInputBase,inputBaseControl} from '../web/input-base.js';
import {newControl,controlMarkup,controlCss,controlWithStates} from '../web/controls.js';
import {sizingMode} from '../web/layout-sizing.js';
await init({module_or_path:await readFile(new URL('../web/pkg/pixlprfct_core_bg.wasm',import.meta.url))});
test('switch starter variables persist, update instances, and retain native semantics',()=>{
 const e=new Editor(),base=ensureInputBase(JSON.parse(e.snapshot()).variables,'switch');
 assert.equal(base.collection.name,'Switch Base');
 assert.equal(ensureInputBase(base.variables,'switch').variables.collections.length,1);
 assert.ok(!base.collection.modes.some(m=>m.name==='Indeterminate'));
 const id=e.insert_control_starter(JSON.stringify({id:0,name:'Switch starter',kind:'frame',x:0,y:0,width:180,height:24,fill:'#ffffff',text:'',hidden:false,control:{...newControl('switch','Notifications'),starter:true,base_collection:base.collection.id},variable_bindings:base.bindings}),JSON.stringify(base.variables));
 const instance=e.create_instance(id,200,0),vars=JSON.parse(e.snapshot()).variables;
 vars.values.find(v=>v.name==='Track / Height').values[1]=32;
 vars.values.find(v=>v.name==='Thumb / Size').values[1]=26;
 e.save_variables(JSON.stringify(vars));
 const get=id=>JSON.parse(e.snapshot()).shapes.find(s=>s.id===id);
 e.update(JSON.stringify({...get(id),control:{...get(id).control,label_position:'left'}}));
 const s=get(instance),c=inputBaseControl(s,vars);
 assert.equal(c.states.default.parts.input.height,32);assert.equal(c.states.default.parts.thumb.size,26);
 assert.equal(c.label_position,'left');assert.equal(sizingMode(s,'height'),'hug');
 assert.match(controlCss(c,instance),/--px-switch-height:32px/);
 assert.match(controlCss(c,instance),/--px-switch-thumb:26px/);
 assert.match(controlCss(c,instance),/justify-content:flex-end/);
 const html=controlMarkup(controlWithStates(c,'selected,disabled'),instance);
 assert.match(html,/role="switch"/);assert.match(html,/type="checkbox"/);assert.match(html,/checked="checked"/);assert.match(html,/disabled="disabled"/);
 assert.match(html,new RegExp('for="px-check-'+instance+'"'));
 const copy=new Editor();copy.load(e.snapshot());assert.equal(JSON.parse(copy.snapshot()).shapes.find(s=>s.id===instance).control.kind,'switch');copy.free();e.free();
});
