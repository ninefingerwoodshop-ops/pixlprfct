test('side icon tokens propagate to instances, respect modes and revert to inherit on deletion',()=>{
 const e=new Editor(),base=ensureInputBase(doc(e).variables),id=insert(e,base),instance=e.create_instance(id,300,0);
 let vars=doc(e).variables;let next=100;
 for(const spec of inputTokens.filter(t=>t.name.startsWith('Left icon /')))vars.values.push(inputTokenVariable(spec,base.collection,next++));
 const color=vars.values.find(v=>v.name==='Left icon / Color'),size=vars.values.find(v=>v.name==='Left icon / Size');
 color.values[1]='#112233';size.values[1]=24;size.values[2]=32;e.save_variables(JSON.stringify(vars));
 assert.equal(shape(e,id).control.left_adornment.color,'#112233');assert.equal(shape(e,instance).control.left_adornment.size,24);
 e.set_page_variable_mode(doc(e).active_page,base.collection.id,2);assert.equal(shape(e,instance).control.left_adornment.size,32);
 vars=doc(e).variables;vars.values=vars.values.filter(v=>![color.id,size.id].includes(v.id));e.save_variables(JSON.stringify(vars));
 assert.equal(shape(e,id).control.left_adornment.color,'');assert.equal(shape(e,instance).control.left_adornment.size,null);
 e.undo();assert.equal(shape(e,instance).control.left_adornment.size,32);e.free();
});

