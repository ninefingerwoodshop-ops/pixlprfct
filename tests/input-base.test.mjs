 const next=ensureInputBase(doc(e).variables);assert.equal(next.collection.name,'Brand inputs');assert.equal(next.variables.collections.length,1);
 const second=insert(e,next);assert.equal(shape(e,second).control.states.default.parts.input.radius,'12');
 const copy=new Editor();copy.load(e.snapshot());assert.equal(doc(copy).variables.collections[0].preset,'input_base');assert.equal(shape(copy,id).control.base_collection,base.collection.id);
