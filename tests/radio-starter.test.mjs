import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import init,{Editor} from '../web/pkg/pixlprfct_core.js';
import {ensureInputBase,inputBaseControl} from '../web/input-base.js';
import {newControl,controlMarkup,controlCss,controlWithStates} from '../web/controls.js';
import {sizingMode} from '../web/layout-sizing.js';
await init({module_or_path:await readFile(new URL('../web/pkg/pixlprfct_core_bg.wasm',import.meta.url))});
test('radio circle and dot variables propagate with labels and native group semantics',()=>{
 const e=new Editor(),base=ensureInputBase(JSON.parse(e.snapshot()).variables,'radio');
 assert.equal(base.collection.name,'Radio Base');assert.equal(ensureInputBase(base.variables,'radio').variables.collections.length,1);
 assert.ok(!base.collection.modes.some(m=>m.name==='Indeterminate'));
 const id=e.insert_control_starter(JSON.stringify({id:0,name:'Radio starter',kind:'frame',x:0,y:0,width:180,height:20,fill:'#ffffff',text:'',hidden:false,control:{...newControl('radio','Option A'),name:'choice',value:'a',starter:true,base_collection:base.collection.id},variable_bindings:base.bindings}),JSON.stringify(base.variables));
 const instance=e.create_instance(id,200,0),get=id=>JSON.parse(e.snapshot()).shapes.find(s=>s.id===id),vars=JSON.parse(e.snapshot()).variables;
 vars.values.find(v=>v.name==='Circle / Size').values[1]=28;vars.values.find(v=>v.name==='Dot / Size').values[1]=14;vars.values.find(v=>v.name==='Dot / Color').values[1]='#123456';e.save_variables(JSON.stringify(vars));
 e.update(JSON.stringify({...get(id),control:{...get(id).control,label_position:'left'}}));
 const s=get(instance),c=inputBaseControl(s,vars),css=controlCss(c,instance);
 assert.equal(sizingMode(s,'height'),'hug');assert.equal(c.label_position,'left');
 assert.match(css,/--px-checkbox-size:28px/);assert.match(css,/--px-radio-dot:14px/);assert.match(css,/border-radius:50%;clip-path:none/);assert.match(css,/background:#123456/);
 const html=controlMarkup(controlWithStates(c,'selected,disabled'),instance);
 assert.match(html,/type="radio"/);assert.match(html,/name="choice"/);assert.match(html,/value="a"/);assert.match(html,/checked="checked"/);assert.match(html,/disabled="disabled"/);assert.match(html,new RegExp('for="px-check-'+instance+'"'));
 e.update(JSON.stringify({...get(instance),control:{...get(instance).control,name:'other-choice',value:'b'}}));
 assert.equal(get(instance).control.name,'other-choice');assert.equal(get(id).control.name,'choice');
 e.free();
});
test('radio starter options form one group and selection can vary per instance',()=>{
 const e=new Editor(),id=e.add('frame',0,0),get=id=>JSON.parse(e.snapshot()).shapes.find(s=>s.id===id);
 e.update(JSON.stringify({...get(id),control:{...newControl('radio','Delivery'),options:['Standard','Express','Pickup'],value:'Express',starter:true}}));e.create_component(id);
 const instance=e.create_instance(id,250,0);e.update(JSON.stringify({...get(instance),control:{...get(instance).control,value:'Pickup'}}));
 const html=controlMarkup(get(instance).control,instance);
 assert.equal((html.match(/type="radio"/g)||[]).length,3);assert.equal((html.match(/checked="checked"/g)||[]).length,1);
 assert.match(html,/role="radiogroup" aria-label="Delivery"/);
 assert.equal((html.match(new RegExp('name="px-radio-group-'+instance+'"','g'))||[]).length,3);
 assert.match(html,/checked="checked" value="Pickup"/);
 assert.equal(get(id).control.value,'Express');
 const css=controlCss(get(instance).control,instance,{interactive:true});assert.match(css,/flex-direction:column;gap:8px/);assert.match(css,/height:max-content/);
 e.update(JSON.stringify({...get(id),control:{...get(id).control,options:['Standard','Express','Pickup','Courier']}}));assert.equal(get(instance).control.options.length,4);
 e.free();
});
